#!/usr/bin/env python3
"""Regenerate docs/BENCHMARKS.md tables from results/*.json, and assert the README numbers match the raw files."""
import json, os, re, statistics as st
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")
CORE = ["q_code", "q_reason", "q_web", "q_3d", "q_agent"]
RUNS = {"RTX 3090, llama.cpp + --lora": "llmbench_rtx3090_llamacpp_lora.json",
        "RTX 3090, EXL3 + DFlash2": "llmbench_rtx3090_exl3.json",
        "RX 7900 XTX, EXL3 + DFlash2 (ROCm)": "llmbench_7900xtx_exl3rocm.json"}
SPEED = {"RTX 3090": "rtx3090-qwen38-pi-exl3_nothink.json", "RX 7900 XTX": "7900xtx-qwen38-pi-exl3rocm_nothink.json"}


def load(f):
    return json.load(open(os.path.join(R, f)))


def speed(f):
    out = {}
    for k, v in load(f)["runs"].items():
        r = v["reps"]
        out[k] = {"tok_s": st.median(x["tok_s"] for x in r), "decode": st.median(x["server_decode_tok_s"] for x in r),
                  "accept": round(100 * sum(x["accepted"] for x in r) / sum(x["accepted"] + x["rejected"] for x in r)),
                  "tokens": r[0]["ct"], "n": len(r)}
    return out


def bench(f):
    d = load(f)
    core = [r for r in d["results"] if r["suite"] in CORE]
    svg = [r for r in d["results"] if r["suite"] == "q_svg"]
    return {"core": round(st.mean(r["score"] for r in core), 3), "svg": round(st.mean(r["score"] for r in svg), 3),
            "suites": {s: round(d["suites"][s]["score"], 3) for s in CORE + ["q_svg"]},
            "wall": round(sum(r["wall_s"] for r in d["results"])), "results": {r["id"]: r for r in d["results"]},
            "agg_tps": (round(sum(r.get("completion_tokens") or 0 for r in d["results"]) / sum(r["wall_s"] for r in d["results"]), 1)
                        if sum(r.get("completion_tokens") or 0 for r in d["results"]) else None)}


def main():
    sp = {k: speed(v) for k, v in SPEED.items()}
    bn = {k: bench(v) for k, v in RUNS.items()}
    nd = load("needle.json")
    L = ["# Benchmarks", "", "All numbers below are generated by `scripts/make_tables.py` from the files in `results/`.", ""]
    L += ["## Decode speed", "", "`bench/bench_api.py`, greedy, thinking off, 512-token replies, 3 repetitions, median.",
          "Whole = completion tokens / whole-request wall time (includes prefill and HTTP). Server decode = TabbyAPI's own",
          "generation rate. Acceptance = accepted / (accepted + rejected) draft tokens over the 3 runs.", "",
          "| card | prompt | whole tok/s | server decode tok/s | draft acceptance |", "|---|---|---|---|---|"]
    for card, rows in sp.items():
        for k, v in rows.items():
            L.append(f"| {card} | {k} | {v['tok_s']} | {v['decode']} | {v['accept']}% |")
    L += ["", "## Long context", "", "Needle (a random 6-digit code) at 97% depth of a random-word filler prompt, greedy.", "",
          "| card | window | cache | prompt tokens | found | prefill tok/s | peak VRAM MiB |", "|---|---|---|---|---|---|---|"]
    for k, v in nd.items():
        pt = v.get("prompt_tokens") or v.get("prompt_tokens_server")
        pf = v.get("prefill_tok_s") or v.get("prefill_tok_s_server")
        L.append(f"| {v['card']} | {v['ctx']} | {v['cache']} | {pt} | {v['found']} | {pf} | {v['peak_vram_mib']} of {v['vram_total_mib']} |")
    L += ["", "## llmbench quick suites", "", "Temperature 0, thinking off, max 8192 tokens. Graders are deterministic (unit tests, exact",
          "match, HTML/SVG/three.js structure checks); no LLM judge.", "",
          "| run | " + " | ".join(CORE + ["q_svg"]) + " | avg of 34 | wall s | tok/s |", "|---|" + "---|" * (len(CORE) + 4)]
    for k, v in bn.items():
        tps = v["agg_tps"] if v["agg_tps"] is not None else "n/a"
        L.append(f"| {k} | " + " | ".join(str(v["suites"][s]) for s in CORE + ["q_svg"]) + f" | {v['core']} | {v['wall']} | {tps} |")
    L += ["", "tok/s = all completion tokens / all wall time over the 40 items. The ROCm TabbyAPI does not return token",
          "counts (`usage` is null), so its llmbench file records 0 tokens and 0 tok/s per item; its scores and wall times",
          "are valid, and its decode speed comes from `bench_api.py` above instead.", "",
          "The llama.cpp row is the adapter as harness-hub ships it (`Qwen3.8-27B-pi-lora-F16.gguf` applied with `--lora`),",
          "on unsloth `Qwen3.8-27B-UD-Q4_K_XL` rather than the Q8_0 base its card recommends (Q8_0 is 28.6 GB and does not fit",
          "a 24 GB card). No draft model."]
    names = list(bn)
    L += ["", "### Items that differ between runs", ""]
    for a, b in [(names[0], names[1]), (names[1], names[2])]:
        ra, rb = bn[a]["results"], bn[b]["results"]
        diffs = [(i, ra[i]["score"], rb[i]["score"]) for i in ra if i in rb and ra[i]["score"] != rb[i]["score"]]
        L.append(f"- {a} -> {b}: " + (", ".join(f"`{i}` {x} -> {y}" for i, x, y in diffs) or "none"))
    L.append("")
    open(os.path.join(R, "..", "docs", "BENCHMARKS.md"), "w").write("\n".join(L) + "\n")

    readme = open(os.path.join(R, "..", "README.md")).read()
    must = [f"{sp['RTX 3090']['code']['tok_s']} tok/s** ({sp['RTX 3090']['code']['accept']}%",
            f"{sp['RX 7900 XTX']['code']['tok_s']} tok/s** ({sp['RX 7900 XTX']['code']['accept']}%",
            f"{sp['RTX 3090']['math']['tok_s']} ({sp['RTX 3090']['math']['accept']}%",
            f"{sp['RX 7900 XTX']['math']['tok_s']} ({sp['RX 7900 XTX']['math']['accept']}%",
            f"{sp['RTX 3090']['prose']['tok_s']} ({sp['RTX 3090']['prose']['accept']}%",
            f"{sp['RX 7900 XTX']['prose']['tok_s']} ({sp['RX 7900 XTX']['prose']['accept']}%",
            f"{nd['rtx3090']['prompt_tokens']:,} tokens", f"{nd['7900xtx']['prompt_tokens_server']:,} tokens"]
    for k, v in bn.items():
        must += [f"| {v['core']:.3f} | ", f"| {v['wall']} s |"]
    lc = bn["RTX 3090, llama.cpp + --lora"]["agg_tps"]
    ex = bn["RTX 3090, EXL3 + DFlash2"]["agg_tps"]
    for m_ in (f"{ex} vs\n{lc} tok/s", f"{round(ex / lc, 1)}x the generation speed", f"| {lc} |", f"| {ex} |"):
        assert m_ in readme, f"README speed claim out of date: {m_!r}"
    missing = [m for m in must if m not in readme]
    assert not missing, f"README out of date: {missing}"
    print("tables written; README numbers match results/")


if __name__ == "__main__":
    main()
